/// Which real-world protocol a resolved liquidity address belongs to.
///
/// Kept deliberately separate from `omega_flashloan::FlashloanProvider` — that enum
/// lives in the crate that owns provider *selection and premium math* (a documented,
/// narrower scope per that crate's own header); this one exists purely so this crate
/// (and the L2e poll loop / validation report) has something to label results with,
/// without omega-rpc taking on a dependency on omega-flashloan or vice versa. Convert
/// at the call site if an `omega_flashloan::FlashloanProvider` is actually needed —
/// don't merge the two enums, or a scope change in one crate silently drags in the
/// other's.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LiquidityProtocol {
    AaveV3,
    BalancerV2,
    /// Added alongside `UNISWAP_V3_WETH_USDC_POOL` and
    /// `fetch_uniswap_v3_pool_balance` — no `resolve_liquidity_addresses` entry
    /// exists for this variant (see that function's own doc comment): Uniswap V3 has
    /// no single canonical contract the way Aave's Pool or Balancer's Vault does, so
    /// there's no equivalent tag-override slot to resolve here today. The L2e loop in
    /// `main.rs` uses `UNISWAP_V3_WETH_USDC_POOL` directly.
    UniswapV3,
}

impl std::fmt::Display for LiquidityProtocol {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            LiquidityProtocol::AaveV3 => write!(f, "aave_v3"),
            LiquidityProtocol::BalancerV2 => write!(f, "balancer_v2"),
            LiquidityProtocol::UniswapV3 => write!(f, "uniswap_v3"),
        }
    }
}

/// A single resolved (query_target, recorded_label) pair for one liquidity provider.
///
/// The distinction between these two fields is the whole point of this struct.
/// `main.rs`'s own module doc comment is explicit that `OMEGA_AAVE_V3_POOL_TAG_OVERRIDE`
/// / `OMEGA_BALANCER_V2_VAULT_TAG_OVERRIDE` "override only the address TAG recorded in
/// LiquidityRegistry — do NOT redirect what the L2e poll's eth_call reads actually
/// target". Collapsing this back into one `Address` would silently reintroduce exactly
/// that bug.
///
/// Uniswap V3 deliberately has no entry here — see `resolve_liquidity_addresses`'s own
/// doc comment.
#[derive(Debug, Clone, Copy)]
pub struct ResolvedLiquidityAddress {
    pub protocol: LiquidityProtocol,
    /// The address `fetch_aave_available` / `fetch_balancer_available` actually query.
    /// NEVER affected by a tag override.
    pub query_target: Address,
    /// The address recorded against a successful poll in
    /// `omega_flashloan::LiquidityRegistry` (via that type's own `update` method, called
    /// from `main.rs`'s L2e loop). Equal to `query_target` unless an env override
    /// relabels it.
    pub recorded_label: Address,
}

/// Resolves the real Aave V3 / Balancer V2 addresses for `chain_id`, applying the
/// tag-override semantics `main.rs`'s env vars already document.
///
/// Returns `None` for any chain other than Arbitrum One — there is deliberately no
/// fallback or "best guess" for other chains, matching `main.rs`'s own posture (its
/// L2d/L2e loops target fixed Arbitrum addresses "regardless of OMEGA_CHAIN_ID" and
/// fail soft rather than silently redirect). Returning `None` here lets the caller
/// decide how to react (warn-and-skip, hard error, etc.) rather than this function
/// making that call.
///
/// SCOPE NOTE: does NOT include Uniswap V3. Aave and Balancer each have exactly one
/// canonical contract per chain, which is what makes a "query real address, but allow
/// relabeling the recorded tag" split meaningful for them. Uniswap V3 has no such
/// single contract — every fee tier / token pair is its own pool — so
/// `UNISWAP_V3_WETH_USDC_POOL` is used directly by callers rather than resolved (and
/// tag-overridden) here. If a second Uniswap pool or asset pair is added later, revisit
/// whether this function's shape still fits or whether Uniswap needs its own resolver.
pub fn resolve_liquidity_addresses(
    chain_id: u64,
    aave_tag_override: Option<Address>,
    balancer_tag_override: Option<Address>,
) -> Option<[ResolvedLiquidityAddress; 2]> {
    if chain_id != ARBITRUM_ONE_CHAIN_ID {
        return None;
    }

    Some([
        ResolvedLiquidityAddress {
            protocol: LiquidityProtocol::AaveV3,
            query_target: AAVE_V3_POOL,
            recorded_label: aave_tag_override.unwrap_or(AAVE_V3_POOL),
        },
        ResolvedLiquidityAddress {
            protocol: LiquidityProtocol::BalancerV2,
            query_target: BALANCER_V2_VAULT,
            recorded_label: balancer_tag_override.unwrap_or(BALANCER_V2_VAULT),
        },
    ])
}

