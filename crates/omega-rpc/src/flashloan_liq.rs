// NOTE: deliberately no `#[sol(rpc)]` here. That attribute generates a typed contract
// `*Instance` wrapper whose `::new(address, provider: P)` requires `P: Provider<T, N>`
// with an IMPLICIT `Sized` bound — confirmed by a real `cargo build` in this session
// (see this file's header, "Fix (this revision, post-build)"): `Arc<dyn Provider>`
// (what `client.rs::get_or_connect()` returns, by design, so the connection can be
// swapped on reconnect) never satisfies that bound, no matter how it's passed in.
// Without `#[sol(rpc)]`, `sol!` still generates the plain `*Call`/`*Return` structs
// (`SolCall::abi_encode`/`abi_decode_returns`) used below — that's all a raw
// `provider.call(&tx)` needs, and `provider.call` is a DIRECT `Provider` trait method
// that dispatches fine on `Arc<dyn Provider>` (same as `get_code`/`fetch_fee_snapshot`
// in client.rs), unlike the `Instance` wrapper's generic constructor.
alloy::sol! {
    interface IErc20Balance {
        function balanceOf(address account) external view returns (uint256);
    }

    interface IAaveProtocolDataProvider {
        function getReserveTokensAddresses(address asset)
            external
            view
            returns (address aTokenAddress, address stableDebtTokenAddress, address variableDebtTokenAddress);
    }
}

