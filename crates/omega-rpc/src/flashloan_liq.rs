/// One address's real, on-chain validation outcome.
#[derive(Debug, Clone)]
pub struct AddressValidation {
    pub label: &'static str,
    pub address: Address,
    /// `true` iff `eth_getCode` returned non-empty bytecode. `false` means either the
    /// address is unused / an EOA, or the RPC call itself failed — see `error` to
    /// distinguish the two.
    pub has_code: bool,
    /// `Some(..)` only when the RPC call itself errored (network, timeout, malformed
    /// response) — distinct from a legitimate empty response, which sets
    /// `has_code = false` with `error = None`.
    pub error: Option<String>,
}

/// Startup validation report for every address this module hardcodes.
#[derive(Debug, Clone)]
pub struct DeploymentValidationReport {
    pub chain_id: u64,
    pub results: Vec<AddressValidation>,
}

impl DeploymentValidationReport {
    /// `true` iff every checked address returned non-empty bytecode with no RPC error.
    ///
    /// DELIBERATE SCOPE LIMIT: this confirms "something is deployed at this address",
    /// not "the correct contract, at the expected version, implementing the expected
    /// ABI, is deployed here" — and, as of `UNISWAP_V3_WETH_USDC_POOL`, not "this is
    /// the pool paired with the token this codebase means" either; see that
    /// constant's own doc comment for why bytecode presence alone would NOT have
    /// caught the wrong-pool trap found this session (the wrong pool has real code
    /// too, it's just the wrong pool). A real ABI-level check (e.g. calling
    /// `getReserveTokensAddresses`/`balanceOf` — the exact calls
    /// `fetch_aave_available`/`fetch_balancer_available`/`fetch_uniswap_v3_pool_balance`
    /// already make — and confirming they don't revert) would close the
    /// bytecode-vs-ABI gap further; those functions effectively ARE that check the
    /// first time the L2e poll loop runs, so a bytecode-only startup check plus
    /// fail-soft-on-first-real-call behavior together cover more ground than either
    /// alone, without this function claiming a stronger guarantee than what it
    /// actually verifies.
    pub fn all_ok(&self) -> bool {
        self.results.iter().all(|r| r.has_code && r.error.is_none())
    }
}

/// Runs a real `eth_getCode` (via `OmegaRpcClient::get_code`) against every hardcoded
/// address in this module, for `chain_id`, and returns a report.
///
/// Intended to be called once at startup so a stale/wrong address is caught as a loud
/// startup failure instead of `fetch_aave_available`/`fetch_balancer_available`/
/// `fetch_uniswap_v3_pool_balance` (or the L2d ArbGasInfo poll) silently failing soft,
/// cycle after cycle, forever. Does NOT panic or bail itself — the caller decides
/// whether `all_ok() == false` should halt startup (recommended — see `main.rs`'s own
/// call site) or just warn.
///
/// For any `chain_id != ARBITRUM_ONE_CHAIN_ID`, returns an empty report (`results` is
/// empty, `all_ok()` trivially `true`) — this module has no addresses to check on
/// another chain, and reporting `all_ok() == true` in that case is correct, not a false
/// positive: there is nothing here to be wrong about off Arbitrum.
pub async fn validate_deployed_contracts(
    rpc: &OmegaRpcClient,
    chain_id: u64,
) -> DeploymentValidationReport {
    if chain_id != ARBITRUM_ONE_CHAIN_ID {
        return DeploymentValidationReport {
            chain_id,
            results: Vec::new(),
        };
    }

    let targets: [(&'static str, Address); 6] = [
        ("AAVE_V3_POOL", AAVE_V3_POOL),
        ("AAVE_PROTOCOL_DATA_PROVIDER", AAVE_PROTOCOL_DATA_PROVIDER),
        ("BALANCER_V2_VAULT", BALANCER_V2_VAULT),
        ("WETH", WETH),
        ("USDC_NATIVE", USDC_NATIVE),
        ("UNISWAP_V3_WETH_USDC_POOL", UNISWAP_V3_WETH_USDC_POOL),
    ];

    let mut results = Vec::with_capacity(targets.len());
    for (label, address) in targets {
        // One RPC call at a time, deliberately not concurrent — this runs once at
        // startup, is not latency-sensitive the way the hot path is, and sequential
        // calls keep each failure's log line unambiguous about which address it was.
        match rpc.get_code(address).await {
            Ok(code) => {
                let has_code = !code.is_empty();
                if !has_code {
                    tracing::error!(
                        label,
                        address = %address,
                        chain_id,
                        "startup validation: no bytecode at hardcoded address — this is \
                         either an EOA, an unused address, or a wrong constant in \
                         omega-rpc/src/flashloan_liq.rs"
                    );
                }
                results.push(AddressValidation {
                    label,
                    address,
                    has_code,
                    error: None,
                });
            }
            Err(e) => {
                tracing::error!(
                    label,
                    address = %address,
                    chain_id,
                    error = %e,
                    "startup validation: eth_getCode failed — cannot confirm this address \
                     is a real deployed contract"
                );
                results.push(AddressValidation {
                    label,
                    address,
                    has_code: false,
                    error: Some(e.to_string()),
                });
            }
        }
    }

    DeploymentValidationReport { chain_id, results }
}

